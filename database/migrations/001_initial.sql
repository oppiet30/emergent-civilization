CREATE TABLE worlds (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(120) NOT NULL,
 seed BIGINT UNSIGNED NOT NULL,
 current_tick BIGINT UNSIGNED NOT NULL DEFAULT 0,
 rng_state BIGINT UNSIGNED NOT NULL,
 status ENUM('paused','running','completed') NOT NULL DEFAULT 'paused',
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;

CREATE TABLE world_tiles (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 world_id BIGINT UNSIGNED NOT NULL,
 x SMALLINT UNSIGNED NOT NULL,
 y SMALLINT UNSIGNED NOT NULL,
 terrain ENUM('grass','forest','water','mountain') NOT NULL,
 movement_cost TINYINT UNSIGNED NOT NULL DEFAULT 1,
 UNIQUE KEY uq_world_xy (world_id,x,y),
 FOREIGN KEY (world_id) REFERENCES worlds(id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE settlements (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 world_id BIGINT UNSIGNED NOT NULL,
 name VARCHAR(120) NOT NULL,
 x SMALLINT UNSIGNED NOT NULL,
 y SMALLINT UNSIGNED NOT NULL,
 food_storage INT UNSIGNED NOT NULL DEFAULT 0,
 wood_storage INT UNSIGNED NOT NULL DEFAULT 0,
 FOREIGN KEY (world_id) REFERENCES worlds(id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE agents (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 world_id BIGINT UNSIGNED NOT NULL,
 settlement_id BIGINT UNSIGNED NULL,
 name VARCHAR(100) NOT NULL,
 x SMALLINT UNSIGNED NOT NULL,
 y SMALLINT UNSIGNED NOT NULL,
 hunger TINYINT UNSIGNED NOT NULL DEFAULT 0,
 energy TINYINT UNSIGNED NOT NULL DEFAULT 100,
 health TINYINT UNSIGNED NOT NULL DEFAULT 100,
 food_inventory INT UNSIGNED NOT NULL DEFAULT 0,
 wood_inventory INT UNSIGNED NOT NULL DEFAULT 0,
 alive BOOLEAN NOT NULL DEFAULT TRUE,
 INDEX idx_world_alive (world_id,alive,id),
 FOREIGN KEY (world_id) REFERENCES worlds(id) ON DELETE CASCADE,
 FOREIGN KEY (settlement_id) REFERENCES settlements(id) ON DELETE SET NULL
) ENGINE=InnoDB;
